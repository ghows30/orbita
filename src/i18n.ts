export const LANGS = [
  { id: 'it', name: 'Italiano', locale: 'it-IT' },
  { id: 'en', name: 'English', locale: 'en-GB' },
  { id: 'es', name: 'Español', locale: 'es-ES' },
  { id: 'de', name: 'Deutsch', locale: 'de-DE' },
] as const;
export type Lang = (typeof LANGS)[number]['id'];

const DICTS: Record<Lang, Dict> = { it, en, es, de };
const KEY = 'orbita.lang';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.some((l) => l.id === saved)) return saved as Lang;
  } catch {
    /* storage non disponibile */
  }
  try {
    for (const n of navigator.languages || [navigator.language]) {
      const p = (n || '').slice(0, 2).toLowerCase();
      if (LANGS.some((l) => l.id === p)) return p as Lang;
    }
  } catch {
    /* fuori dal browser (test) */
  }
  return 'en';
}

let lang: Lang = detect();
if (typeof document !== 'undefined') document.documentElement.lang = lang;

export const currentLang = () => lang;
/** Locale per date e numeri (it-IT, en-GB, …). */
export const locale = () => LANGS.find((l) => l.id === lang)!.locale;

export function setLang(l: Lang) {
  lang = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* resta valida solo per questa sessione */
  }
}

/** Traduce una chiave sostituendo i segnaposto {nome}. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang][key] ?? it[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Numero formattato secondo la lingua scelta. */
export const num = (n: number) => n.toLocaleString(locale());

// Messaggi di errore che arrivano già scritti in italiano dal server Node o dal codice nativo:
// li riconosciamo e li traduciamo, così il protocollo resta compatibile con gli APK già installati.
const REMOTE: [RegExp, Key][] = [
  [/^Errore di rete verso il provider/, 'err.network'],
  [/^Il provider ha risposto con errore (\d+)/, 'err.providerHttp'],
  [/^Guida EPG non disponibile \((\d+)\)/, 'err.epg'],
  [/^Sessione stream scaduta/, 'err.session'],
  [/^Stream non disponibile \((\d+)\)/, 'pl.unavailable'],
  [/^Indirizzo non consentito/, 'err.blocked'],
  [/^Risposta del provider troppo grande|^Risposta troppo grande/, 'err.tooBig'],
  [/^Server del provider non trovato/, 'err.noHost'],
  [/^Il provider non risponde/, 'err.timeout'],
  [/^Connessione rifiutata/, 'err.refused'],
  [/^Connessione sicura non riuscita/, 'err.ssl'],
  [/^Richiesta scaduta/, 'err.expired'],
  [/^(URL non valido|Richiesta non valida|JSON non valido|Richiesta non autorizzata|Metodo non consentito)/, 'err.badRequest'],
];
export function translateRemote(msg: string): string {
  for (const [re, key] of REMOTE) {
    const m = re.exec(msg);
    if (m) return t(key, { c: m[1] ?? '' });
  }
  return msg;
}
